import { EUR_LABELS, USD_LABELS, PLN_LABELS, findPair, findPairByValue } from "./parser.mjs";
import assert from "node:assert";
const lb = "Currency\tBuy\tSell\nEuro\nEUR\t143.57\t144.68\t-\nUnited State dollar\nUSD\t132.93\t133.96\t−0.05%\nPolish zloty\nPLN\t34.414\t34.803\t0.18%";
assert.deepStrictEqual(findPair(lb, EUR_LABELS, 144, 0.04), [143.57, 144.68]);
assert.deepStrictEqual(findPair(lb, USD_LABELS, 133, 0.04), [132.93, 133.96]);
assert.deepStrictEqual(findPair(lb, PLN_LABELS, 34.6, 0.04), [34.414, 34.803]);
const fx = "Aktualny kurs EUR/PLN\nPara walutowa\nSPRZEDAJ\n4,2312\nKUP\n4,2598";
assert.deepStrictEqual(findPair(fx, EUR_LABELS, 4.245, 0.04), [4.2312, 4.2598]);
const arion = "Buy\tSell\n144.55\t145.52\t-0.12\n175.07\t176.30\n34.41\t34.80";
assert.deepStrictEqual(findPairByValue(arion, 145, 0.03), [144.55, 145.52]);
assert.deepStrictEqual(findPair("Visa\nPLN\t34.71", PLN_LABELS, 34.6, 0.04, 1), [34.71, 34.71]);
console.log("parser tests OK");
import { labels } from "./parser.mjs";
const multi = "Currency\tBuy\tSell\nEUR\t143.57\t144.68\nGBP\t163.10\t164.20\nNOK\t12.41\t12.52\nSEK\t11.88\t12.01\nJPY\t0.8811\t0.8901";
assert.deepStrictEqual(findPair(multi, labels("GBP"), 163.8, 0.04), [163.1, 164.2]);
assert.deepStrictEqual(findPair(multi, labels("NOK"), 12.5, 0.04), [12.41, 12.52]);
assert.deepStrictEqual(findPair(multi, labels("SEK"), 12.0, 0.04), [11.88, 12.01]);
assert.deepStrictEqual(findPair(multi, labels("JPY"), 0.885, 0.04), [0.8811, 0.8901]);
assert.strictEqual(findPair(multi, labels("UAH"), 2.78, 0.04), null);
console.log("multi-currency tests OK");
